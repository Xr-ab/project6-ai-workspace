# ---- Phase 2 RAG：启用知识库检索时用的提示词 ----

# 启用知识库时**替换** SYSTEM_PROMPT，而不是追加。
# 为什么必须替换：RAG 的核心约束是"只依据资料"，这和通用助手"自由发挥"
# 的行为方向相反。两条提示词叠在一起，模型会两边都想满足 ——
# 结果是既编造、又不标引用，这是 RAG 最典型的失败模式。
RAG_SYSTEM_PROMPT = """你是一个企业 AI 工作台助手，正在依据检索到的资料回答问题。要求：
1. 只依据给出的资料回答，不要用资料之外的知识补充；
2. 资料里找不到答案时，直接回答"资料中没有相关内容"，绝不编造；
3. 引用了某条资料时，在对应句子末尾标注它的编号，如 [1]、[2]；
4. 简洁准确，用中文回答。"""

# 资料块的包装文字。用拼接而不是 str.format：
# 资料正文里可能出现花括号（代码、JSON），format 会把它当占位符直接报错。
RAG_CONTEXT_HEADER = "以下是检索到的资料："
RAG_CONTEXT_FOOTER = "请依据以上资料回答用户的问题。"

# ---- Phase 3 Tool Calling：启用工具时**追加**到 system 末尾的规则 ----
#
# 为什么是追加、而不是像 RAG_SYSTEM_PROMPT 那样替换：
#     工具不改变回答的立场（仍然是"依据事实、不许编造"），只是多了一条获取事实的
#     途径，和通用助手 / RAG 两套规则都不冲突。唯一的例外是 RAG 那句
#     "不要用资料之外的知识补充" —— 不澄清的话模型会把它理解成"不许调工具"，
#     于是明明给了工具却一次都不用。所以第 2 条专门点明这层区别。
#
# 四种组合（通用 / RAG / 工具 / RAG+工具）都靠"基础提示词 + 这条"覆盖，
# 不必为每种组合各写一份 —— 组合数一多，改一处就漏一处。
TOOL_RULES = """另外，你可以调用工具来获取事实。要求：
1. 需要查公司内部资料、查业务数据、做精确计算、看文件内容时，先调用相应工具，不要凭记忆作答；
2. 上一条"不要用资料之外的知识补充"指的是不要拿记忆和常识编造，调用工具补查不在此列；
3. 工具没返回结果、或执行失败时，如实说明"没有查到"，不要编造；
4. 拿到足够信息就直接作答，不要反复调用同一个工具；
5. 全程用中文作答，包括调用工具前后的一句说明；不要输出英文句子。"""

